"""Profiles (which user-scope Kiro configuration loads) and the agent definition a session's settings become."""

from __future__ import annotations

import hashlib
import json
import logging
import os
import shutil
import tempfile
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any, TypeAlias

logger = logging.getLogger(__name__)


@dataclass(frozen=True)
class Inherit:
    """The user's own Kiro configuration (``~/.kiro``, or ``$KIRO_HOME``): behaves like their Kiro CLI."""


@dataclass(frozen=True)
class Isolated:
    """A library-managed KIRO_HOME: none of the user's agents, steering, MCP servers or rules load.

    ``path=None`` is a temporary directory removed on close. With a path, sessions stored there can be loaded
    by later runs; a new directory is created readable by its owner only. The login works either way:
    credentials live outside KIRO_HOME.
    """

    path: str | os.PathLike[str] | None = None


Profile: TypeAlias = Inherit | Isolated


def _strings(name: str, values: Sequence[str]) -> list[str]:
    if not isinstance(values, str):
        items = list(values)
        if all(isinstance(v, str) for v in items):
            return items
    raise TypeError(f"{name} is a sequence of strings, e.g. ['shell'], got {values!r}")


def agent_definition(
    system: str | None, kiro_tools: Sequence[str] | None, allow: Sequence[str], deny: Sequence[str]
) -> dict[str, Any] | None:
    """A Kiro agent definition for ``_meta.kiro.customAgents``, with an id derived from its content.

    The strings go to Kiro unchanged. Returns None when no setting is given.

    Raises:
        TypeError: ``system`` is not a string, or ``kiro_tools``, ``allow`` or ``deny`` is not a sequence of strings.
    """
    if system is not None and not isinstance(system, str):
        raise TypeError(f"system is a string, got {system!r}")
    tools = ["*"] if kiro_tools is None else _strings("kiro_tools", kiro_tools)
    allow, deny = _strings("allow", allow), _strings("deny", deny)
    if system is None and kiro_tools is None and not allow and not deny:
        return None
    rules = [{"capability": c, "effect": "allow"} for c in allow] + [{"capability": c, "effect": "deny"} for c in deny]
    agent = {"prompt": system or "", "tools": tools, "permissions": {"rules": rules}}
    digest = hashlib.sha256(json.dumps(agent, sort_keys=True).encode()).hexdigest()[:12]
    return {"id": f"pykiro-{digest}", "description": "Agent generated by pykiro", **agent}


def validate_home(path: Path) -> Path:
    """Reject paths for which Kiro silently uses ``~/.kiro`` instead, turning isolation into inherit."""
    path = path.expanduser().resolve()
    home = Path.home().resolve()
    user_home = Path(os.environ.get("KIRO_HOME") or home / ".kiro").expanduser().resolve()
    if path in (Path(path.anchor), home, user_home) or path in home.parents:
        raise ValueError(f"{path} can't be an isolated KIRO_HOME (root, home, an ancestor, or ~/.kiro)")
    return path


class ProfileHome:
    """The KIRO_HOME a client runs with; ``path`` is None for Inherit."""

    def __init__(self, profile: Profile) -> None:
        """Resolve (and for Isolated, create) the home for ``profile``.

        Raises:
            TypeError: ``profile`` is not an ``Inherit()`` or ``Isolated(...)`` instance.
        """
        if not isinstance(profile, Inherit | Isolated):  # anything else must not silently inherit
            raise TypeError(f"profile must be Inherit() or Isolated(...), got {profile!r}")
        self.path: Path | None = None
        self.ephemeral = isinstance(profile, Isolated) and profile.path is None
        if isinstance(profile, Isolated):
            if profile.path is None:
                self.path = Path(tempfile.mkdtemp(prefix="pykiro-"))
            else:
                self.path = validate_home(Path(profile.path))
                self.path.mkdir(mode=0o700, parents=True, exist_ok=True)  # an existing directory keeps its mode

    def cleanup(self) -> None:
        """Remove an ephemeral home; a failure is logged, not raised."""
        if not self.ephemeral or self.path is None:
            return
        try:
            shutil.rmtree(self.path)
        except OSError as exc:
            logger.warning("path=<%s>, error=<%s> | could not remove the temporary KIRO_HOME", self.path, exc)
